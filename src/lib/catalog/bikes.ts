function withCatalogEnrichment(bike: CatalogBikeVariant): CatalogBikeVariant {
  let next = bike;
  if ((next.frameAttributes?.length ?? 0) === 0) {
    const frameId = next.oemComponents?.frame;
    const frame = frameId ? getComponentModel(frameId) : undefined;
    if (frame?.attributes.length) {
      next = { ...next, frameAttributes: frame.attributes };
    }
  }
  const geo = BIKE_GEOMETRY[next.id];
  if (geo?.length && !(next.geometryBySize?.length)) {
    next = { ...next, geometryBySize: geo };
  }
  return next;
}

export const BIKE_CATALOG: CatalogManufacturer[] = BIKE_CATALOG_RAW.map((m) => ({
  ...m,
  bikes: m.bikes.map(withCatalogEnrichment),
}));

export function findCatalogBike(id: string) {
  for (const m of BIKE_CATALOG) {
    const bike = m.bikes.find((b) => b.id === id);
    if (bike) return { manufacturer: m, bike };
  }
  return undefined;
}

function shortDriveLabel(modelId: string | undefined): string | undefined {
  if (!modelId) return undefined;
  const m = getComponentModel(modelId);
  if (!m) return undefined;
  const blob = `${m.model} ${m.variant ?? ""}`;
  if (m.slot === "motor") {
    if (/\bCX\b/i.test(blob) && /\bRace\b/i.test(blob)) {
      return `${m.manufacturer} CX Race`;
    }
    if (/\bCX\b/i.test(blob)) return `${m.manufacturer} CX`;
    return `${m.manufacturer} ${m.model.replace(/^Performance Line\s+/i, "")}`.trim();
  }
  if (m.slot === "battery") {
    const wh = m.attributes.find((a) => a.key === "capacity_wh")?.valueNum;
    if (wh != null) return `${wh} Wh`;
  }
  return [m.manufacturer, m.model].filter(Boolean).join(" ");
}

/** Antrieb aus Katalog-Identität — ohne OEM-Stückliste am Rad. */
export function catalogDriveIdentity(catalogBikeId?: string | null): {
  motor?: string;
  battery?: string;
} {
  if (!catalogBikeId) return {};
  const found = findCatalogBike(catalogBikeId);
  if (!found) return {};
  const oem = found.bike.oemComponents;
  return {
    motor: shortDriveLabel(oem.motor),
    battery: shortDriveLabel(oem.battery),
  };
}

export function catalogGeometryForSize(
  bikeId: string,
  size: string | undefined
) {
  return geometryForSize(
    findCatalogBike(bikeId)?.bike.geometryBySize,
    size
  );
}

export function listCatalogManufacturers() {
  return BIKE_CATALOG;
}

export function catalogStats() {
  const manufacturers = BIKE_CATALOG.length;
  const bikes = BIKE_CATALOG.reduce((n, m) => n + m.bikes.length, 0);
  const oemRefs = BIKE_CATALOG.reduce(
    (n, m) =>
      n +
      m.bikes.reduce(
        (bn, b) => bn + Object.keys(b.oemComponents ?? {}).length,
        0
      ),
    0
  );
  return { manufacturers, bikes, oemRefs };
}
